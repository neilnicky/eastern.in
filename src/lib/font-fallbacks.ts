/**
 * Metric-matched fallback faces for the two web fonts. While Fraunces or Figtree is still downloading the browser
 * paints text in a system face; scaling that face (`size-adjust`) and moving its baseline (`ascent/descent/line-gap-override`)
 * to the web font's metrics makes the later swap move almost nothing, which is what caused the cookbook page's CLS.
 *
 * Vertical overrides are derived from the font files (capsize formulas). `size-adjust` is measured on the site's real text by
 * `scripts/measure-fallback-width.ts`, because the average-glyph-width shortcut is wrong for Fraunces at its `opsz` 144
 * display setting. The committed output is src/styles/font-fallbacks.css; regenerate it with `pnpm font-fallbacks`.
 */
export interface FaceMetrics {
  ascent: number;
  descent: number;
  lineGap: number;
  unitsPerEm: number;
}

export interface FallbackSpec {
  family: string;
  style?: "italic";
  /** System faces to try, in order. Each must be the face `system` metrics describe. */
  local: string[];
  web: FaceMetrics;
  system: FaceMetrics;
  /** Web-font width ÷ system-font width on the site's text (1 = same width). */
  sizeAdjust: number;
}

/**
 * Measured with scripts/measure-fallback-width.ts on the built site (412px viewport, 11 representative pages).
 * `fraunces` is the display setting (opsz 144) that titles use. Text set at a small optical size (opsz 24-48) is wider
 * relative to Times New Roman (~105%), so it gets its own face, `Fraunces Text Fallback`, via `--font-serif-text`.
 */
export const SIZE_ADJUST = { fraunces: 0.928, frauncesText: 1.054, frauncesItalic: 1.075, figtree: 0.983 };

const pct = (n: number) => `${(Math.round(n * 1000) / 10).toString()}%`;

export function fallbackFace(spec: FallbackSpec): string {
  const { web, system, sizeAdjust } = spec;
  // Overrides are expressed against the web font's em, so divide out the size-adjust the browser applies afterwards.
  const ascent = web.ascent / (web.unitsPerEm * sizeAdjust);
  const descent = Math.abs(web.descent) / (web.unitsPerEm * sizeAdjust);
  const lineGap = web.lineGap / (web.unitsPerEm * sizeAdjust);
  return `@font-face {
  font-family: "${spec.family}";${spec.style ? `\n  font-style: ${spec.style};` : ""}
  src: ${spec.local.map((l) => `local("${l}")`).join(", ")};
  size-adjust: ${pct(sizeAdjust)};
  ascent-override: ${pct(ascent)};
  descent-override: ${pct(descent)};
  line-gap-override: ${pct(lineGap)};
}
`;
}

export function fontFallbackCss(m: { fraunces: FaceMetrics; frauncesItalic: FaceMetrics; figtree: FaceMetrics; timesNewRoman: FaceMetrics; arial: FaceMetrics }): string {
  return `/* Generated by \`pnpm font-fallbacks\` from src/lib/font-fallbacks.ts. Do not edit. */
${fallbackFace({ family: "Fraunces Fallback", local: ["Times New Roman", "TimesNewRomanPSMT"], web: m.fraunces, system: m.timesNewRoman, sizeAdjust: SIZE_ADJUST.fraunces })}
${fallbackFace({ family: "Fraunces Text Fallback", local: ["Times New Roman", "TimesNewRomanPSMT"], web: m.fraunces, system: m.timesNewRoman, sizeAdjust: SIZE_ADJUST.frauncesText })}
${fallbackFace({ family: "Fraunces Fallback", style: "italic", local: ["Times New Roman Italic", "TimesNewRomanPS-ItalicMT"], web: m.frauncesItalic, system: m.timesNewRoman, sizeAdjust: SIZE_ADJUST.frauncesItalic })}
${fallbackFace({ family: "Figtree Fallback", local: ["Arial", "ArialMT"], web: m.figtree, system: m.arial, sizeAdjust: SIZE_ADJUST.figtree })}`;
}
