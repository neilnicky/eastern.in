import { SPICES } from "./spices";
import type { SpiceName } from "@/content/types";

/**
 * CSS custom properties holding each spice silhouette as an SVG data-URI, for use as `mask-image`.
 * Product tiles draw their hover shapes with these masks on pseudo-elements (inside `@media (hover: hover)`),
 * so touch devices render no shape elements at all. The committed output is src/styles/spice-masks.css;
 * regenerate it with `pnpm spice-masks` (tests/unit/spice-masks.test.ts fails if it drifts from spices.ts).
 */
export function spiceMaskCss(): string {
  const lines = (Object.keys(SPICES) as SpiceName[]).map((name) => {
    const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'><polygon points='${SPICES[name].points}'/></svg>`;
    return `  --spice-${name}: url("data:image/svg+xml,${encodeURIComponent(svg)}");`;
  });
  return `/* Generated by scripts/write-spice-masks.ts from src/lib/spices.ts. Do not edit by hand. */\n:root {\n${lines.join("\n")}\n}\n`;
}
