// Writes public/_redirects (Netlify / Cloudflare Pages format) from src/content/redirects.ts so hosts that
// support it answer retired URLs with a real 301. Astro also emits meta-refresh pages for other hosts.
import fs from "node:fs";
import { legacyRedirects } from "../src/content/redirects.ts";
const lines = Object.entries(legacyRedirects).map(([from, { status, destination }]) => `${from} ${destination} ${status}\n${from.replace(/\/$/, "")} ${destination} ${status}`);
fs.writeFileSync(new URL("../public/_redirects", import.meta.url), `# Generated by scripts/write-redirects.mjs — do not edit by hand\n${lines.join("\n")}\n`);
console.log("redirects", Object.keys(legacyRedirects).length);
